//! Crash-safe, versioned JSON storage.
//!
//! Every file is written atomically: the new content goes to a temporary file
//! in the same folder, is flushed to disk, the previous good copy is kept as
//! `<name>.bak`, and the temporary file is renamed over the original. A crash
//! at any point leaves either the old file or the new one, never a half file.
//! Reads fall back to the `.bak` copy if the main file is missing or damaged.

use std::fs::{self, File, OpenOptions};
use std::io::{Read, Seek, SeekFrom, Write};
use std::path::{Path, PathBuf};

use serde::de::DeserializeOwned;
use serde::{Deserialize, Serialize};

use crate::error::{CoreError, Result};

/// Every saved file is wrapped in this envelope so it can be upgraded later.
#[derive(Debug, Serialize, Deserialize)]
pub struct Envelope<T> {
    #[serde(rename = "schemaVersion")]
    pub schema_version: u32,
    pub data: T,
}

/// Physical layout inside the app data folder (Planning Update 04, section 7).
#[derive(Debug, Clone)]
pub struct DataRoot {
    root: PathBuf,
}

impl DataRoot {
    pub fn new(root: impl Into<PathBuf>) -> Result<Self> {
        let root = root.into();
        for dir in ["application", "accounts", "students", "administration/audit-log", "administration/recovery", "backups"] {
            fs::create_dir_all(root.join(dir))?;
        }
        Ok(Self { root })
    }

    pub fn path(&self) -> &Path {
        &self.root
    }

    pub fn accounts(&self, file: &str) -> PathBuf {
        self.root.join("accounts").join(file)
    }

    pub fn application(&self, file: &str) -> PathBuf {
        self.root.join("application").join(file)
    }

    pub fn audit_dir(&self) -> PathBuf {
        self.root.join("administration").join("audit-log")
    }

    pub fn backups_dir(&self) -> PathBuf {
        self.root.join("backups")
    }

    pub fn students_dir(&self) -> PathBuf {
        self.root.join("students")
    }

    /// The folder that holds one student's records. Only valid student ids
    /// (generated by this crate) are accepted, so this can't escape the root.
    pub fn student_dir(&self, student_id: &str) -> Result<PathBuf> {
        validate_id(student_id)?;
        Ok(self.students_dir().join(student_id))
    }

    /// Resolves a student record by logical name, e.g. `progress` or
    /// `checkpoints/lesson-01`. The interface never supplies file paths.
    pub fn student_record(&self, student_id: &str, record: &str) -> Result<PathBuf> {
        validate_record_name(record)?;
        Ok(self.student_dir(student_id)?.join(format!("{record}.json")))
    }
}

/// Student ids are 32 lowercase hex characters.
pub fn validate_id(id: &str) -> Result<()> {
    if id.len() == 32 && id.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)) {
        Ok(())
    } else {
        Err(CoreError::InvalidName(id.to_string()))
    }
}

/// Record names: one or two segments of `[a-z0-9-]`, separated by `/`.
pub fn validate_record_name(name: &str) -> Result<()> {
    let segments: Vec<&str> = name.split('/').collect();
    let ok = !name.is_empty()
        && name.len() <= 80
        && segments.len() <= 2
        && segments.iter().all(|s| {
            !s.is_empty() && s.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-') && !s.starts_with('-')
        });
    if ok { Ok(()) } else { Err(CoreError::InvalidName(name.to_string())) }
}

fn bak_path(path: &Path) -> PathBuf {
    let mut s = path.as_os_str().to_owned();
    s.push(".bak");
    PathBuf::from(s)
}

fn tmp_path(path: &Path) -> PathBuf {
    let mut s = path.as_os_str().to_owned();
    s.push(".tmp");
    PathBuf::from(s)
}

pub(crate) fn sync_dir(dir: &Path) {
    // Directory fsync makes the rename durable on Linux/Android. Windows does
    // not support opening directories this way; NTFS rename is durable enough.
    #[cfg(unix)]
    if let Ok(d) = File::open(dir) {
        let _ = d.sync_all();
    }
    #[cfg(not(unix))]
    let _ = dir;
}

/// Atomically replaces `path` with `bytes`, keeping the previous copy as `.bak`.
pub fn atomic_write(path: &Path, bytes: &[u8]) -> Result<()> {
    let dir = path.parent().ok_or_else(|| CoreError::InvalidName(path.display().to_string()))?;
    fs::create_dir_all(dir)?;
    let tmp = tmp_path(path);
    {
        let mut f = OpenOptions::new().write(true).create(true).truncate(true).open(&tmp)?;
        f.write_all(bytes)?;
        f.sync_all()?;
    }
    if path.exists() {
        // Keep the last good copy. Copy (not rename) so `path` always exists.
        let bak = bak_path(path);
        let _ = fs::remove_file(&bak);
        fs::copy(path, &bak)?;
    }
    fs::rename(&tmp, path)?;
    sync_dir(dir);
    Ok(())
}

// ----- Append-only logs (JSON Lines) -----------------------------------------
//
// Attempts, mastery events, the XP ledger and the audit log are append-only
// files with one JSON value per line. A crash during an append can leave an
// unfinished last line. Recovery rules:
//
// - Every append writes the record and its newline in one write, then
//   flushes, so a record is only ever followed by its own newline.
// - Before appending, the end of the file is checked. If the last line is
//   unfinished:
//   - a complete JSON object that only lost its newline is kept, and the
//     newline is added (nothing is duplicated: the record is not re-written);
//   - anything else is the fragment of an interrupted write. Its bytes are
//     copied to `<log>.damaged` (one JSON line each: offset, length, text and
//     exact hex), then cut from the log, so the next record starts on a line
//     of its own and no valid record is ever glued onto damaged bytes.
// - Readers report what they could not use ([`LogRead::damaged`]) instead of
//   dropping it silently, and recover records that an earlier version glued
//   onto a crash fragment ([`LogRead::salvaged`]).

/// Where damaged log fragments are kept, next to the log.
pub fn damaged_path(path: &Path) -> PathBuf {
    let mut s = path.as_os_str().to_owned();
    s.push(".damaged");
    PathBuf::from(s)
}

/// Appends one record (one line) to an append-only log and flushes it,
/// first repairing an unfinished last line left by a crash (see above).
pub fn append_line(path: &Path, line: &str) -> Result<()> {
    if line.contains('\n') {
        return Err(CoreError::InvalidData("log lines cannot contain newlines".into()));
    }
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    repair_log_tail(path)?;
    let mut record = Vec::with_capacity(line.len() + 1);
    record.extend_from_slice(line.as_bytes());
    record.push(b'\n');
    let mut f = OpenOptions::new().create(true).append(true).open(path)?;
    f.write_all(&record)?;
    f.sync_all()?;
    Ok(())
}

fn parse_object(bytes: &[u8]) -> Option<serde_json::Value> {
    serde_json::from_slice::<serde_json::Value>(bytes).ok().filter(|v| v.is_object())
}

/// Makes sure the log ends with a complete line (see the rules above).
/// Returns quickly when the file is missing, empty or already ends in a newline.
fn repair_log_tail(path: &Path) -> Result<()> {
    let mut f = match OpenOptions::new().read(true).write(true).open(path) {
        Ok(f) => f,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(e) => return Err(e.into()),
    };
    if f.metadata()?.len() == 0 {
        return Ok(());
    }
    let mut last = [0u8; 1];
    f.seek(SeekFrom::End(-1))?;
    f.read_exact(&mut last)?;
    if last[0] == b'\n' {
        return Ok(());
    }
    // Rare path (only after a crash): find where the unfinished line starts.
    let mut bytes = Vec::new();
    f.seek(SeekFrom::Start(0))?;
    f.read_to_end(&mut bytes)?;
    let start = bytes.iter().rposition(|&b| b == b'\n').map_or(0, |i| i + 1);
    let tail = &bytes[start..];
    if parse_object(tail).is_some() {
        // The record was written in full; only its newline is missing.
        f.seek(SeekFrom::End(0))?;
        f.write_all(b"\n")?;
    } else {
        quarantine_fragment(path, start as u64, tail)?;
        f.set_len(start as u64)?;
    }
    f.sync_all()?;
    Ok(())
}

/// Copies a damaged fragment to `<log>.damaged` before it is cut from the log.
fn quarantine_fragment(path: &Path, offset: u64, fragment: &[u8]) -> Result<()> {
    let entry = serde_json::json!({
        "offset": offset,
        "length": fragment.len(),
        "text": String::from_utf8_lossy(fragment),
        "hex": fragment.iter().map(|b| format!("{b:02x}")).collect::<String>(),
    });
    let line = entry.to_string();
    let q = damaged_path(path);
    // A crash after this copy but before the cut repeats the repair on the
    // next append; the same fragment is not recorded twice.
    if let Ok(existing) = fs::read_to_string(&q) {
        if existing.lines().last() == Some(line.as_str()) {
            return Ok(());
        }
    }
    let mut f = OpenOptions::new().create(true).append(true).open(&q)?;
    f.write_all(format!("{line}\n").as_bytes())?;
    f.sync_all()?;
    Ok(())
}

/// The records of an append-only log, in the order they were written.
#[derive(Debug, Default)]
pub struct LogRead {
    pub records: Vec<serde_json::Value>,
    /// Lines that were not valid JSON: an unfinished last line from an
    /// interrupted write (moved to `.damaged` by the next append), or older
    /// damaged lines. A salvaged line also counts here.
    pub damaged: usize,
    /// Records recovered from lines where an earlier version appended a
    /// record directly after a crash fragment.
    pub salvaged: usize,
}

/// Reads an append-only log (see the recovery rules above).
pub fn read_log_file(path: &Path) -> Result<LogRead> {
    let bytes = match fs::read(path) {
        Ok(b) => b,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(LogRead::default()),
        Err(e) => return Err(e.into()),
    };
    let mut out = LogRead::default();
    let mut lines: Vec<&[u8]> = bytes.split(|&b| b == b'\n').collect();
    // The piece after the last newline: empty for a complete file, otherwise
    // an unfinished line. It is a record only if it is a whole JSON object,
    // which is exactly what the next append keeps.
    let tail = lines.pop().unwrap_or(&[]);
    for line in lines {
        if line.is_empty() {
            continue;
        }
        if let Ok(v) = serde_json::from_slice::<serde_json::Value>(line) {
            out.records.push(v);
            continue;
        }
        out.damaged += 1;
        // A record glued onto a fragment is the longest suffix that is a
        // whole JSON object.
        let salvaged = line.iter().enumerate().skip(1).filter(|&(_, &b)| b == b'{').find_map(|(i, _)| parse_object(&line[i..]));
        if let Some(v) = salvaged {
            out.records.push(v);
            out.salvaged += 1;
        }
    }
    if !tail.is_empty() {
        match parse_object(tail) {
            Some(v) => out.records.push(v),
            None => out.damaged += 1,
        }
    }
    Ok(out)
}

/// Which copy a read came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReadSource {
    Main,
    Backup,
}

/// Reads raw JSON, falling back to the `.bak` copy if the main file is
/// missing or not valid JSON. Returns `None` if neither exists.
pub fn read_json_value(path: &Path) -> Result<Option<(serde_json::Value, ReadSource)>> {
    let try_read = |p: &Path| -> Option<serde_json::Value> {
        let bytes = fs::read(p).ok()?;
        serde_json::from_slice(&bytes).ok()
    };
    if let Some(v) = try_read(path) {
        return Ok(Some((v, ReadSource::Main)));
    }
    let bak = bak_path(path);
    if let Some(v) = try_read(&bak) {
        return Ok(Some((v, ReadSource::Backup)));
    }
    if path.exists() {
        return Err(CoreError::Corrupt(path.display().to_string()));
    }
    Ok(None)
}

/// A migration step upgrades data from version `n` to `n + 1`.
pub type Migration = fn(serde_json::Value) -> Result<serde_json::Value>;

/// Reads a versioned file, applying migrations up to `current`. `migrations[i]`
/// upgrades version `i + 1` to `i + 2`. Files from a newer app version are
/// refused rather than misread.
pub fn read_versioned<T: DeserializeOwned>(path: &Path, current: u32, migrations: &[Migration]) -> Result<Option<T>> {
    let Some((value, _)) = read_json_value(path)? else { return Ok(None) };
    let version = value.get("schemaVersion").and_then(|v| v.as_u64()).ok_or_else(|| CoreError::Corrupt(path.display().to_string()))? as u32;
    if version > current {
        return Err(CoreError::NewerVersion { found: version, supported: current });
    }
    let mut data = value.get("data").cloned().ok_or_else(|| CoreError::Corrupt(path.display().to_string()))?;
    for v in version..current {
        let step = migrations.get((v - 1) as usize).ok_or(CoreError::NewerVersion { found: version, supported: current })?;
        data = step(data)?;
    }
    Ok(Some(serde_json::from_value(data).map_err(|e| CoreError::InvalidData(e.to_string()))?))
}

pub fn write_versioned<T: Serialize>(path: &Path, version: u32, data: &T) -> Result<()> {
    let env = Envelope { schema_version: version, data };
    let bytes = serde_json::to_vec_pretty(&env).map_err(|e| CoreError::InvalidData(e.to_string()))?;
    atomic_write(path, &bytes)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn record_names_cannot_escape() {
        for bad in ["", "../x", "a/../b", "a\\b", "A", "a/b/c", "-a", "a b", "a.json", "/a"] {
            assert!(validate_record_name(bad).is_err(), "{bad} should be rejected");
        }
        for good in ["progress", "mastery-events", "checkpoints/lesson-01"] {
            assert!(validate_record_name(good).is_ok());
        }
        assert!(validate_id("../../etc").is_err());
        assert!(validate_id("0123456789abcdef0123456789abcdef").is_ok());
    }

    #[test]
    fn atomic_write_keeps_backup_and_recovers_from_corruption() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("x.json");
        write_versioned(&p, 1, &json!({"n": 1})).unwrap();
        write_versioned(&p, 1, &json!({"n": 2})).unwrap();
        // Simulate a damaged main file (e.g. disk error): backup is used.
        fs::write(&p, b"{not json").unwrap();
        let (v, src) = read_json_value(&p).unwrap().unwrap();
        assert_eq!(src, ReadSource::Backup);
        assert_eq!(v["data"]["n"], 1);
    }

    #[test]
    fn leftover_temp_file_from_crash_is_ignored() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("x.json");
        write_versioned(&p, 1, &json!({"n": 1})).unwrap();
        // Crash after writing the temp file but before the rename.
        fs::write(tmp_path(&p), b"{\"schemaVersion\":1,\"data\":{\"n\":").unwrap();
        let v: serde_json::Value = read_versioned(&p, 1, &[]).unwrap().unwrap();
        assert_eq!(v["n"], 1);
        // The next write replaces the stale temp file.
        write_versioned(&p, 1, &json!({"n": 3})).unwrap();
        let v: serde_json::Value = read_versioned(&p, 1, &[]).unwrap().unwrap();
        assert_eq!(v["n"], 3);
    }

    #[test]
    fn migrations_upgrade_old_files_and_newer_files_are_refused() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("x.json");
        write_versioned(&p, 1, &json!({"name": "a"})).unwrap();
        let m1: Migration = |mut v| {
            v["displayName"] = v["name"].take();
            Ok(v)
        };
        let v: serde_json::Value = read_versioned(&p, 2, &[m1]).unwrap().unwrap();
        assert_eq!(v["displayName"], "a");
        write_versioned(&p, 9, &json!({})).unwrap();
        assert!(matches!(read_versioned::<serde_json::Value>(&p, 2, &[m1]), Err(CoreError::NewerVersion { .. })));
    }

    fn log_text(p: &Path) -> String {
        fs::read_to_string(p).unwrap()
    }

    fn values(r: &LogRead) -> Vec<i64> {
        r.records.iter().map(|v| v["a"].as_i64().unwrap()).collect()
    }

    /// Simulates a crash part-way through an append: some bytes, no newline.
    fn crash_mid_write(p: &Path, bytes: &[u8]) {
        let mut f = OpenOptions::new().create(true).append(true).open(p).unwrap();
        f.write_all(bytes).unwrap();
    }

    #[test]
    fn append_log_reports_partial_last_line() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("log.jsonl");
        append_line(&p, "{\"a\":1}").unwrap();
        append_line(&p, "{\"a\":2}").unwrap();
        crash_mid_write(&p, b"{\"a\":3");
        let r = read_log_file(&p).unwrap();
        assert_eq!(values(&r), [1, 2]);
        assert_eq!(r.damaged, 1, "the unfinished line is reported, not hidden");
        assert!(append_line(&p, "a\nb").is_err());
    }

    #[test]
    fn interrupted_write_never_swallows_the_next_record() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("log.jsonl");
        append_line(&p, "{\"a\":1}").unwrap();
        append_line(&p, "{\"a\":2}").unwrap();
        let offset = fs::metadata(&p).unwrap().len();
        crash_mid_write(&p, b"{\"a\":3,\"note\":\"half");
        append_line(&p, "{\"a\":4}").unwrap();
        // Before the fix this read [1, 2]: record 4 was glued onto the fragment.
        let r = read_log_file(&p).unwrap();
        assert_eq!(values(&r), [1, 2, 4], "valid records kept, in order, none lost");
        assert_eq!((r.damaged, r.salvaged), (0, 0));
        assert_eq!(log_text(&p), "{\"a\":1}\n{\"a\":2}\n{\"a\":4}\n");
        // The fragment is kept for inspection, not silently discarded.
        let q: Vec<serde_json::Value> = log_text(&damaged_path(&p)).lines().map(|l| serde_json::from_str(l).unwrap()).collect();
        assert_eq!(q.len(), 1);
        assert_eq!(q[0]["offset"], offset);
        assert_eq!(q[0]["text"], "{\"a\":3,\"note\":\"half");
        append_line(&p, "{\"a\":5}").unwrap();
        assert_eq!(values(&read_log_file(&p).unwrap()), [1, 2, 4, 5]);
        assert_eq!(log_text(&damaged_path(&p)).lines().count(), 1, "repair runs once");
    }

    #[test]
    fn a_complete_record_that_lost_its_newline_is_kept_once() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("log.jsonl");
        append_line(&p, "{\"a\":1}").unwrap();
        crash_mid_write(&p, b"{\"a\":2}"); // crash between the record and its newline
        assert_eq!(values(&read_log_file(&p).unwrap()), [1, 2], "readable before the next append");
        append_line(&p, "{\"a\":3}").unwrap();
        let r = read_log_file(&p).unwrap();
        assert_eq!(values(&r), [1, 2, 3], "kept, in order, not duplicated");
        assert_eq!(r.damaged, 0);
        assert!(!damaged_path(&p).exists());
    }

    #[test]
    fn a_crash_during_the_very_first_write_is_recovered() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("log.jsonl");
        crash_mid_write(&p, b"{\"a\"");
        append_line(&p, "{\"a\":1}").unwrap();
        assert_eq!(log_text(&p), "{\"a\":1}\n");
        assert!(log_text(&damaged_path(&p)).contains("\"offset\":0"));
    }

    #[test]
    fn a_crash_during_repair_does_not_record_the_fragment_twice() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("log.jsonl");
        append_line(&p, "{\"a\":1}").unwrap();
        let offset = fs::metadata(&p).unwrap().len();
        crash_mid_write(&p, b"{\"a\":");
        // Crash after copying the fragment but before cutting it from the log.
        quarantine_fragment(&p, offset, b"{\"a\":").unwrap();
        append_line(&p, "{\"a\":2}").unwrap();
        assert_eq!(values(&read_log_file(&p).unwrap()), [1, 2]);
        assert_eq!(log_text(&damaged_path(&p)).lines().count(), 1);
    }

    #[test]
    fn records_glued_onto_fragments_by_earlier_versions_are_salvaged() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("log.jsonl");
        fs::write(&p, "{\"a\":1}\n{\"a\":2,\"x\":{\"y\":1}{\"a\":3}\nnot json\n{\"a\":4}\n").unwrap();
        let r = read_log_file(&p).unwrap();
        assert_eq!(values(&r), [1, 3, 4]);
        assert_eq!((r.damaged, r.salvaged), (2, 1));
    }
}
