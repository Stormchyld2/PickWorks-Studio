//! Crash-safe, versioned JSON storage.
//!
//! Every file is written atomically: the new content goes to a temporary file
//! in the same folder, is flushed to disk, the previous good copy is kept as
//! `<name>.bak`, and the temporary file is renamed over the original. A crash
//! at any point leaves either the old file or the new one, never a half file.
//! Reads fall back to the `.bak` copy if the main file is missing or damaged.

use std::fs::{self, File, OpenOptions};
use std::io::Write;
use std::path::{Path, PathBuf};

use serde::de::DeserializeOwned;
use serde::{Deserialize, Serialize};

use crate::error::{CoreError, Result};

/// Every saved file is wrapped in this envelope so it can be upgraded later.
#[derive(Debug, Serialize, Deserialize)]
pub struct Envelope<T> {
    #[serde(rename = "schemaVersion")]
    pub schema_version: u32,
    pub data: T,
}

/// Physical layout inside the app data folder (Planning Update 04, section 7).
#[derive(Debug, Clone)]
pub struct DataRoot {
    root: PathBuf,
}

impl DataRoot {
    pub fn new(root: impl Into<PathBuf>) -> Result<Self> {
        let root = root.into();
        for dir in ["application", "accounts", "students", "administration/audit-log", "administration/recovery", "backups"] {
            fs::create_dir_all(root.join(dir))?;
        }
        Ok(Self { root })
    }

    pub fn path(&self) -> &Path {
        &self.root
    }

    pub fn accounts(&self, file: &str) -> PathBuf {
        self.root.join("accounts").join(file)
    }

    pub fn application(&self, file: &str) -> PathBuf {
        self.root.join("application").join(file)
    }

    pub fn audit_dir(&self) -> PathBuf {
        self.root.join("administration").join("audit-log")
    }

    pub fn backups_dir(&self) -> PathBuf {
        self.root.join("backups")
    }

    pub fn students_dir(&self) -> PathBuf {
        self.root.join("students")
    }

    /// The folder that holds one student's records. Only valid student ids
    /// (generated by this crate) are accepted, so this can't escape the root.
    pub fn student_dir(&self, student_id: &str) -> Result<PathBuf> {
        validate_id(student_id)?;
        Ok(self.students_dir().join(student_id))
    }

    /// Resolves a student record by logical name, e.g. `progress` or
    /// `checkpoints/lesson-01`. The interface never supplies file paths.
    pub fn student_record(&self, student_id: &str, record: &str) -> Result<PathBuf> {
        validate_record_name(record)?;
        Ok(self.student_dir(student_id)?.join(format!("{record}.json")))
    }
}

/// Student ids are 32 lowercase hex characters.
pub fn validate_id(id: &str) -> Result<()> {
    if id.len() == 32 && id.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)) {
        Ok(())
    } else {
        Err(CoreError::InvalidName(id.to_string()))
    }
}

/// Record names: one or two segments of `[a-z0-9-]`, separated by `/`.
pub fn validate_record_name(name: &str) -> Result<()> {
    let segments: Vec<&str> = name.split('/').collect();
    let ok = !name.is_empty()
        && name.len() <= 80
        && segments.len() <= 2
        && segments.iter().all(|s| {
            !s.is_empty() && s.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-') && !s.starts_with('-')
        });
    if ok { Ok(()) } else { Err(CoreError::InvalidName(name.to_string())) }
}

fn bak_path(path: &Path) -> PathBuf {
    let mut s = path.as_os_str().to_owned();
    s.push(".bak");
    PathBuf::from(s)
}

fn tmp_path(path: &Path) -> PathBuf {
    let mut s = path.as_os_str().to_owned();
    s.push(".tmp");
    PathBuf::from(s)
}

fn sync_dir(dir: &Path) {
    // Directory fsync makes the rename durable on Linux/Android. Windows does
    // not support opening directories this way; NTFS rename is durable enough.
    #[cfg(unix)]
    if let Ok(d) = File::open(dir) {
        let _ = d.sync_all();
    }
    #[cfg(not(unix))]
    let _ = dir;
}

/// Atomically replaces `path` with `bytes`, keeping the previous copy as `.bak`.
pub fn atomic_write(path: &Path, bytes: &[u8]) -> Result<()> {
    let dir = path.parent().ok_or_else(|| CoreError::InvalidName(path.display().to_string()))?;
    fs::create_dir_all(dir)?;
    let tmp = tmp_path(path);
    {
        let mut f = OpenOptions::new().write(true).create(true).truncate(true).open(&tmp)?;
        f.write_all(bytes)?;
        f.sync_all()?;
    }
    if path.exists() {
        // Keep the last good copy. Copy (not rename) so `path` always exists.
        let bak = bak_path(path);
        let _ = fs::remove_file(&bak);
        fs::copy(path, &bak)?;
    }
    fs::rename(&tmp, path)?;
    sync_dir(dir);
    Ok(())
}

/// Appends one line and flushes it. Used for append-only logs (attempts,
/// mastery events, XP ledger, audit log): a crash can only lose the last line.
pub fn append_line(path: &Path, line: &str) -> Result<()> {
    if line.contains('\n') {
        return Err(CoreError::InvalidData("log lines cannot contain newlines".into()));
    }
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    let mut f = OpenOptions::new().create(true).append(true).open(path)?;
    f.write_all(line.as_bytes())?;
    f.write_all(b"\n")?;
    f.sync_all()?;
    Ok(())
}

/// Reads an append-only log, skipping a damaged final line (from a crash).
pub fn read_lines(path: &Path) -> Result<Vec<String>> {
    match fs::read_to_string(path) {
        Ok(s) => {
            let mut lines: Vec<String> = s.lines().map(str::to_string).collect();
            if !s.ends_with('\n') {
                lines.pop(); // incomplete last line
            }
            Ok(lines)
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Vec::new()),
        Err(e) => Err(e.into()),
    }
}

/// Which copy a read came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReadSource {
    Main,
    Backup,
}

/// Reads raw JSON, falling back to the `.bak` copy if the main file is
/// missing or not valid JSON. Returns `None` if neither exists.
pub fn read_json_value(path: &Path) -> Result<Option<(serde_json::Value, ReadSource)>> {
    let try_read = |p: &Path| -> Option<serde_json::Value> {
        let bytes = fs::read(p).ok()?;
        serde_json::from_slice(&bytes).ok()
    };
    if let Some(v) = try_read(path) {
        return Ok(Some((v, ReadSource::Main)));
    }
    let bak = bak_path(path);
    if let Some(v) = try_read(&bak) {
        return Ok(Some((v, ReadSource::Backup)));
    }
    if path.exists() {
        return Err(CoreError::Corrupt(path.display().to_string()));
    }
    Ok(None)
}

/// A migration step upgrades data from version `n` to `n + 1`.
pub type Migration = fn(serde_json::Value) -> Result<serde_json::Value>;

/// Reads a versioned file, applying migrations up to `current`. `migrations[i]`
/// upgrades version `i + 1` to `i + 2`. Files from a newer app version are
/// refused rather than misread.
pub fn read_versioned<T: DeserializeOwned>(path: &Path, current: u32, migrations: &[Migration]) -> Result<Option<T>> {
    let Some((value, _)) = read_json_value(path)? else { return Ok(None) };
    let version = value.get("schemaVersion").and_then(|v| v.as_u64()).ok_or_else(|| CoreError::Corrupt(path.display().to_string()))? as u32;
    if version > current {
        return Err(CoreError::NewerVersion { found: version, supported: current });
    }
    let mut data = value.get("data").cloned().ok_or_else(|| CoreError::Corrupt(path.display().to_string()))?;
    for v in version..current {
        let step = migrations.get((v - 1) as usize).ok_or(CoreError::NewerVersion { found: version, supported: current })?;
        data = step(data)?;
    }
    Ok(Some(serde_json::from_value(data).map_err(|e| CoreError::InvalidData(e.to_string()))?))
}

pub fn write_versioned<T: Serialize>(path: &Path, version: u32, data: &T) -> Result<()> {
    let env = Envelope { schema_version: version, data };
    let bytes = serde_json::to_vec_pretty(&env).map_err(|e| CoreError::InvalidData(e.to_string()))?;
    atomic_write(path, &bytes)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn record_names_cannot_escape() {
        for bad in ["", "../x", "a/../b", "a\\b", "A", "a/b/c", "-a", "a b", "a.json", "/a"] {
            assert!(validate_record_name(bad).is_err(), "{bad} should be rejected");
        }
        for good in ["progress", "mastery-events", "checkpoints/lesson-01"] {
            assert!(validate_record_name(good).is_ok());
        }
        assert!(validate_id("../../etc").is_err());
        assert!(validate_id("0123456789abcdef0123456789abcdef").is_ok());
    }

    #[test]
    fn atomic_write_keeps_backup_and_recovers_from_corruption() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("x.json");
        write_versioned(&p, 1, &json!({"n": 1})).unwrap();
        write_versioned(&p, 1, &json!({"n": 2})).unwrap();
        // Simulate a damaged main file (e.g. disk error): backup is used.
        fs::write(&p, b"{not json").unwrap();
        let (v, src) = read_json_value(&p).unwrap().unwrap();
        assert_eq!(src, ReadSource::Backup);
        assert_eq!(v["data"]["n"], 1);
    }

    #[test]
    fn leftover_temp_file_from_crash_is_ignored() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("x.json");
        write_versioned(&p, 1, &json!({"n": 1})).unwrap();
        // Crash after writing the temp file but before the rename.
        fs::write(tmp_path(&p), b"{\"schemaVersion\":1,\"data\":{\"n\":").unwrap();
        let v: serde_json::Value = read_versioned(&p, 1, &[]).unwrap().unwrap();
        assert_eq!(v["n"], 1);
        // The next write replaces the stale temp file.
        write_versioned(&p, 1, &json!({"n": 3})).unwrap();
        let v: serde_json::Value = read_versioned(&p, 1, &[]).unwrap().unwrap();
        assert_eq!(v["n"], 3);
    }

    #[test]
    fn migrations_upgrade_old_files_and_newer_files_are_refused() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("x.json");
        write_versioned(&p, 1, &json!({"name": "a"})).unwrap();
        let m1: Migration = |mut v| {
            v["displayName"] = v["name"].take();
            Ok(v)
        };
        let v: serde_json::Value = read_versioned(&p, 2, &[m1]).unwrap().unwrap();
        assert_eq!(v["displayName"], "a");
        write_versioned(&p, 9, &json!({})).unwrap();
        assert!(matches!(read_versioned::<serde_json::Value>(&p, 2, &[m1]), Err(CoreError::NewerVersion { .. })));
    }

    #[test]
    fn append_log_skips_partial_last_line() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("log.jsonl");
        append_line(&p, "{\"a\":1}").unwrap();
        append_line(&p, "{\"a\":2}").unwrap();
        let mut f = OpenOptions::new().append(true).open(&p).unwrap();
        f.write_all(b"{\"a\":3").unwrap(); // crash mid-line
        assert_eq!(read_lines(&p).unwrap().len(), 2);
        assert!(append_line(&p, "a\nb").is_err());
    }
}
